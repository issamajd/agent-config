#!/usr/bin/env bash
# install.sh - compose the agent-config layers (common -> profile -> machine)
# into ~/.claude and ~/.codex. Idempotent: re-run any time.
#
#   first run:   ./install.sh --machine <name> --profile <profile>
#   later runs:  ./install.sh
#   optional:    ./install.sh --autosync      (login job that runs sync.sh)
#                ./install.sh --no-autosync   (remove it)
set -euo pipefail

REPO="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd -P)"
# shellcheck source=lib/os.sh
. "$REPO/lib/os.sh"

usage() { sed -n '2,9p' "$0" | sed 's/^# \{0,1\}//'; }

MACHINE="" PROFILE="" AUTOSYNC=""
while [ $# -gt 0 ]; do
  case "$1" in
    --machine) MACHINE="$2"; shift 2 ;;
    --profile) PROFILE="$2"; shift 2 ;;
    --autosync) AUTOSYNC=on; shift ;;
    --no-autosync) AUTOSYNC=off; shift ;;
    -h|--help) usage; exit 0 ;;
    *) echo "unknown option: $1" >&2; usage; exit 2 ;;
  esac
done

CLAUDE_DIR="${CLAUDE_CONFIG_DIR:-$HOME/.claude}"
CODEX_DIR="${CODEX_HOME:-$HOME/.codex}"
BACKUP="$CLAUDE_DIR/backups/agent-config-$(date +%Y%m%d-%H%M%S)"
MARKER="generated by agent-config/install.sh"

# Move a pre-existing file or folder out of the way before we replace it.
backup() {
  mkdir -p "$BACKUP"
  mv "$1" "$BACKUP/$(basename "$1")"
  echo "  backed up $1 -> $BACKUP/"
}

# Write stdin to $1 only if the content changed.
write_if_changed() {
  local tmp; tmp="$(mktemp)"
  cat >"$tmp"
  if [ -f "$1" ] && cmp -s "$tmp" "$1"; then rm "$tmp"; return 0; fi
  if [ -f "$1" ] && ! grep -q "$MARKER" "$1"; then backup "$1"; fi
  mkdir -p "$(dirname "$1")"
  mv "$tmp" "$1"
  echo "  wrote $1"
}

# Remove links in $1 that point into the repo but are not in the wanted list $2.
prune_links() {
  local dest="$1" wanted=" $2 " e name
  for e in "$dest"/*; do
    [ -L "$e" ] || continue
    name="$(basename "$e")"
    case "$(readlink "$e")" in "$REPO"/*) ;; *) continue ;; esac
    case "$wanted" in *" $name "*) ;; *) unlink_dir "$e" ;; esac
  done
}

# ---------------------------------------------------------------- machine & profile
if [ -n "$MACHINE" ]; then printf '%s\n' "$MACHINE" >"$REPO/.machine"; fi
if [ ! -f "$REPO/.machine" ]; then
  echo "No machine name yet. Run: ./install.sh --machine <name> --profile <profile>" >&2; exit 2
fi
MACHINE="$(cat "$REPO/.machine")"
MDIR="$REPO/machines/$MACHINE"
if [ -n "$PROFILE" ]; then mkdir -p "$MDIR"; printf 'profile=%s\n' "$PROFILE" >"$MDIR/machine.conf"; fi
if [ ! -f "$MDIR/machine.conf" ]; then
  echo "machines/$MACHINE/machine.conf is missing. Pass --profile <name> once." >&2; exit 2
fi
PROFILE="$(sed -n 's/^profile=//p' "$MDIR/machine.conf" | tr -d '\r')"
if [ ! -d "$REPO/profiles/$PROFILE" ]; then
  echo "profiles/$PROFILE does not exist. Create it (see README) or pick another with --profile." >&2; exit 2
fi

LAYERS=("$REPO/common" "$REPO/profiles/$PROFILE" "$MDIR")
LAYER_NAMES=(common "profile-$PROFILE" "machine-$MACHINE")
echo "agent-config: os=$OS machine=$MACHINE profile=$PROFILE"

# ---------------------------------------------------------------- skills
# install_skills <dest> <audience>...   audiences: shared claude codex
install_skills() {
  local dest="$1"; shift
  local wanted="" layer aud d name
  mkdir -p "$dest"
  for layer in "${LAYERS[@]}"; do
    for aud in "$@"; do
      for d in "$layer/skills/$aud"/*/; do
        d="${d%/}"
        [ -f "$d/SKILL.md" ] || continue
        name="$(basename "$d")"
        if [ -e "$dest/$name" ] && [ ! -L "$dest/$name" ]; then backup "$dest/$name"; fi
        link_dir "$dest/$name" "$d"
        wanted="$wanted $name"
      done
    done
  done
  prune_links "$dest" "$wanted"
}

echo "skills -> $CLAUDE_DIR/skills"
install_skills "$CLAUDE_DIR/skills" shared claude
echo "skills -> $CODEX_DIR/skills"
install_skills "$CODEX_DIR/skills" shared codex

# ---------------------------------------------------------------- Claude subagents
# Claude discovers agents recursively, so each layer's agents/ is linked as a subfolder.
echo "agents -> $CLAUDE_DIR/agents"
install_agents() {
  local dest="$CLAUDE_DIR/agents" wanted="" i src f
  mkdir -p "$dest"
  for i in 0 1 2; do
    src="${LAYERS[$i]}/agents"
    [ -d "$src" ] || continue
    for f in "$src"/*.md; do   # a loose copy with the same name would duplicate the linked one
      [ -f "$f" ] || continue
      if [ -f "$dest/$(basename "$f")" ] && [ ! -L "$dest/$(basename "$f")" ]; then backup "$dest/$(basename "$f")"; fi
    done
    link_dir "$dest/${LAYER_NAMES[$i]}" "$src"
    wanted="$wanted ${LAYER_NAMES[$i]}"
  done
  prune_links "$dest" "$wanted"
}
install_agents

# ---------------------------------------------------------------- helper scripts
# Skills and agents call helpers by a fixed path (~/.claude/bin/<name>), so the
# whole folder is one link into common/bin. A loose copy there is backed up first.
echo "bin -> $CLAUDE_DIR/bin"
if [ -e "$CLAUDE_DIR/bin" ] && [ ! -L "$CLAUDE_DIR/bin" ]; then backup "$CLAUDE_DIR/bin"; fi
link_dir "$CLAUDE_DIR/bin" "$REPO/common/bin"

# ---------------------------------------------------------------- ~/.claude/CLAUDE.md (imports)
echo "CLAUDE.md -> $CLAUDE_DIR/CLAUDE.md"
{
  echo "This file is $MARKER. Edit the imported files in $(native_path "$REPO") instead; imports are read live."
  echo
  for layer in "${LAYERS[@]}"; do
    if [ -f "$layer/claude.md" ]; then echo "@$(native_path "$layer/claude.md")"; fi
  done
} | write_if_changed "$CLAUDE_DIR/CLAUDE.md"

# ---------------------------------------------------------------- ~/.codex/AGENTS.md (concatenated)
echo "AGENTS.md -> $CODEX_DIR/AGENTS.md"
{
  echo "<!-- $MARKER. Edit the layer files in $(native_path "$REPO") and re-run install.sh (sync.sh does this). -->"
  for layer in "${LAYERS[@]}"; do
    [ -f "$layer/agents.md" ] || continue
    echo
    echo "<!-- layer: ${layer#"$REPO"/} -->"
    cat "$layer/agents.md"
  done
} | write_if_changed "$CODEX_DIR/AGENTS.md"

# ---------------------------------------------------------------- repo housekeeping
git -C "$REPO" config core.hooksPath hooks

case "$AUTOSYNC" in
  on) echo "autosync"; register_login_job "$REPO" ;;
  off) echo "autosync"; unregister_login_job ;;
esac

echo "done."
[ -d "$BACKUP" ] && echo "Replaced items were moved to $BACKUP"
exit 0
